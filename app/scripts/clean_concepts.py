def plain(s):
    s = html.unescape(str(s or ''))
    s = re.sub(r'\*\*(.+?)\*\*', r'\1', s)
    s = re.sub(r'__(.+?)__', r'\1', s)
    s = re.sub(r'`([^`]+)`', r'\1', s)
    return re.sub(r'\s+', ' ', s.replace('**', '').replace('`', '')).strip()

def clean(data):
    for c in data['concepts']:
        for f in ('title', 'short', 'why', 'core'):
            c[f] = plain(c.get(f, ''))
    if data['subject'] == 'alg':
        by = {c['id']: c for c in data['concepts']}
        for i, want in ALG_TITLE_CHECK.items():
            assert want in by[i]['title'], f'알고리즘 개념 번호가 바뀌었어: {i} {by[i]["title"]}'
        for i, (why, core) in ALG_CARD.items():
            by[i]['why'], by[i]['core'] = why, core
        for i, why in ALG_WHY.items():
            by[i]['why'] = why
    for s in data['scenes'].values():
        s['title'] = plain(s['title'])
        if 'text' in s: s['text'] = html.unescape(s['text'])
    for L in data['lessons']:
        for f in ('title', 'meta'):
            if L.get(f): L[f] = plain(L[f])
    for ch in data['chapters']:
        ch['title'] = plain(ch['title'])
    # 교재 인쇄 오류를 옮겨 온 문제 고치기
    q = data['quizzes'].get('t8-5-3')
    if q and q['options'][1] == q['options'][2]:
        q['options'][2] = '가, 나, 라'; q['answer'] = [2]
        q['expl']['3'] = '나는 <b>폴링</b> 설명이라 빠져야 해.'
        q['tail'] = '교재에는 ②와 ③이 똑같이 인쇄돼 있어서 ③을 고쳤어.'
    q = data['quizzes'].get('t8-3-3')
    if q:   # (나)의 답은 ISR → "ISR로"
        for f in ('stem', 'question_text'): q[f] = q[f].replace('(나)으로', '(나)로')
    bad = [c['id'] for c in data['concepts'] if re.search(r'[🎒📜🛵]|&[a-z]+;|\*\*', c['why'] + c['core'] + c['title'])]
    assert not bad, f'아직 지저분한 개념: {bad}'
    return data

if __name__ == '__main__':
    root = pathlib.Path(__file__).resolve().parent.parent
    for key in ('tcs', 'alg'):
        p = root / 'data' / f'{key}.json'
        d = clean(json.loads(p.read_text(encoding='utf-8')))
        p.write_text(json.dumps(d, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')
        print(key, 'ok')
